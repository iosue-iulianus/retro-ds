#!/usr/bin/env python3
"""Embeds the UI fonts (assets/fonts) in src/fonts_data.c.

    tools/embed_fonts.py

Barlow (https://github.com/jpt/barlow) is under the SIL Open Font License
1.1 (assets/fonts/Barlow-OFL.txt), which allows bundling it.
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONTS = [("barlow_bold", "Barlow-700-Bold.ttf"), ("barlow_medium", "Barlow-500-Medium.ttf"),
         # the Chinese interfaces' faces (tools/make_zh_font.py): used for the characters Barlow lacks
         ("noto_sc_bold", "NotoSansSC-Bold-subset.ttf"), ("noto_sc_regular", "NotoSansSC-Regular-subset.ttf"),
         ("noto_tc_bold", "NotoSansTC-Bold-subset.ttf"), ("noto_tc_regular", "NotoSansTC-Regular-subset.ttf"),
         ("noto_jp_bold", "NotoSansJP-Bold-subset.ttf"), ("noto_jp_regular", "NotoSansJP-Regular-subset.ttf"),
         ("noto_kr_bold", "NotoSansKR-Bold-subset.ttf"), ("noto_kr_regular", "NotoSansKR-Regular-subset.ttf")]

lines = ["/* Generated by tools/embed_fonts.py - do not edit.", " * Barlow, Noto Sans SC, TC, JP and KR: SIL Open Font License 1.1 (OFL files in assets/fonts) */",
         '#include "fonts_data.h"', ""]
for name, fn in FONTS:
    data = open(os.path.join(ROOT, "assets", "fonts", fn), "rb").read()
    lines.append(f"static const unsigned char {name}_ttf[{len(data)}] = {{")
    for i in range(0, len(data), 24):
        lines.append("\t" + ",".join(str(b) for b in data[i:i + 24]) + ",")
    lines.append("};")
lines.append("")
lines.append("const EmbeddedFont embeddedFonts[EMBEDDED_FONT_COUNT] = {")
for name, _ in FONTS:
    lines.append(f"\t{{ {name}_ttf, sizeof({name}_ttf) }},")
lines.append("};")
with open(os.path.join(ROOT, "src", "fonts_data.c"), "w") as f:
    f.write("\n".join(lines) + "\n")
print("src/fonts_data.c:", ", ".join(fn for _, fn in FONTS))
